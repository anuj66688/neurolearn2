import {
  AgentInput,
  AgentOutput,
  StudyPlan,
  StudyTask,
  StudentProfile,
  PerformanceData,
} from '../types';
import { demoStudyPlan } from '../data/demoData';

export interface StudyPlannerInputPayload {
  studentId: string;
  profile: StudentProfile;
  performance: PerformanceData;
  availableHours?: number;
  triggerEvent?: string;
}

export class StudyPlannerAgent {
  public readonly agentType = 'studyPlanner';
  private studyPlan: StudyPlan = { ...demoStudyPlan };

  public async execute(
    input: AgentInput<StudyPlannerInputPayload>
  ): Promise<AgentOutput<StudyPlan>> {
    const startTime = performance.now();
    const { profile, performance: perf, availableHours = 2.5 } = input.payload;

    const currentTasks = [...this.studyPlan.tasks];
    const weakTopics = perf.weaknesses;

    // Adaptive reallocation: Elevate weak topics to top priority
    for (const weakTopic of weakTopics) {
      const existingTask = currentTasks.find((t) => t.topicName.includes(weakTopic));
      if (existingTask) {
        existingTask.priority = 'high';
        existingTask.durationMinutes = Math.min(existingTask.durationMinutes + 15, 60);
        existingTask.adaptiveReason = `Study Planner Agent escalated priority and added 15 mins due to recent performance dip`;
      } else {
        const newTask: StudyTask = {
          id: `task-adapt-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`,
          title: `Intervention Review: ${weakTopic}`,
          subjectId: 'sub-cn',
          subjectName: 'Computer Networks',
          topicId: weakTopic,
          topicName: weakTopic,
          durationMinutes: 35,
          priority: 'high',
          status: 'pending',
          scheduledDate: new Date().toISOString().split('T')[0],
          adaptiveReason: `Auto-generated by Study Planner Agent to resolve diagnostic deficit`,
        };
        currentTasks.unshift(newTask);
      }
    }

    // Demote or complete mastered topics
    for (const strongTopic of perf.strengths) {
      const strongTask = currentTasks.find((t) => t.topicName.includes(strongTopic));
      if (strongTask && strongTask.priority === 'high') {
        strongTask.priority = 'low';
        strongTask.durationMinutes = 20;
        strongTask.adaptiveReason = `Duration decreased by Study Planner Agent: Topic already mastered (${strongTopic})`;
      }
    }

    const updatedPlan: StudyPlan = {
      id: `plan-${Date.now()}`,
      studentId: profile.id,
      generatedDate: new Date().toISOString(),
      availableHoursPerDay: availableHours,
      targetExamDate: profile.targetExam ? '2026-11-15' : undefined,
      tasks: currentTasks,
      priorityTopics: weakTopics.length > 0 ? weakTopics : ['OSI Model', 'Binary Trees'],
      weeklyGoals: [
        `Achieve >75% mastery in ${weakTopics[0] || 'all target topics'}`,
        'Complete scheduled diagnostic assessments on time',
        `Maintain active study pace: ${availableHours}h daily`,
      ],
      adaptabilityNote: `Adaptive cycle triggered: ${weakTopics.length} priority interventions rescheduled.`,
    };

    this.studyPlan = updatedPlan;

    const executionTimeMs = Math.round(performance.now() - startTime);

    return {
      agentType: 'studyPlanner',
      success: true,
      data: updatedPlan,
      message: `Adaptive study plan updated with ${updatedPlan.tasks.length} balanced study tasks.`,
      executionTimeMs,
      timestamp: new Date().toISOString(),
      nextRecommendedAgents: ['progress'],
    };
  }

  public getStudyPlan(): StudyPlan {
    return this.studyPlan;
  }

  public toggleTaskStatus(taskId: string): StudyPlan {
    this.studyPlan.tasks = this.studyPlan.tasks.map((t) => {
      if (t.id === taskId) {
        const nextStatus = t.status === 'completed' ? 'pending' : 'completed';
        return { ...t, status: nextStatus };
      }
      return t;
    });
    return this.studyPlan;
  }
}

export const studyPlannerAgent = new StudyPlannerAgent();
